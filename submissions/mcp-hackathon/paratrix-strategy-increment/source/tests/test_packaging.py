def test_write_failure_removes_partial_package(project, tmp_path, monkeypatch):
    original_write = Path.write_bytes
    target = tmp_path / "review"
    count = 0

    def fail_second_file(path, content):
        nonlocal count
        count += 1
        if count == 2:
            raise OSError("injected disk failure")
        return original_write(path, content)

    monkeypatch.setattr(Path, "write_bytes", fail_second_file)
    with pytest.raises(OSError, match="injected disk failure"):
        packaging.package_submission(target, project=project)
    assert count == 2
    assert not target.exists()
    assert (project / "source/app/main.py").exists()


def test_copy_uses_the_bytes_that_passed_the_scan(project, tmp_path, monkeypatch):
    original_collect = packaging._collect

    def mutate_after_scan(path):
        checked = original_collect(path)
        (path / "source/app/main.py").write_text("changed after scan")
        return checked

    monkeypatch.setattr(packaging, "_collect", mutate_after_scan)
    target = tmp_path / "review"
    packaging.package_submission(target, project=project)
    assert (target / "source/app/main.py").read_text() == "print('review source')\n"


def committed_release(project):
    (project / "submission.json").unlink()
    config = {"schemaVersion": 1, "slug": "example-project", "apiBaseUrl": "https://example.com/v1"}
    (project / "submission-config.json").write_text(json.dumps(config))
    (project / "SUBMISSION.md").write_text("# Example capability\n")

    def git(*args):
        return subprocess.check_output(["git", *args], cwd=project, stderr=subprocess.PIPE).decode().strip()

    git("init", "-q")
    git("update-index", "--add", "source/app/main.py", "submission-config.json", "SUBMISSION.md")
    git("-c", "user.name=Packaging Test", "-c", "user.email=test@example.com",
        "-c", "commit.gpgsign=false", "commit", "-qm", "Reviewed source")
    return git("rev-parse", "HEAD")


def test_manifest_binds_actual_clean_release_without_self_reference(project, tmp_path):
    commit = committed_release(project)
    target = tmp_path / "review"
    result = packaging.package_submission(target, project=project)
    manifest = json.loads((target / "submission.json").read_text())
    assert manifest["reviewCommit"] == commit
    assert manifest["apiBaseUrl"] == "https://example.com/v1"
    assert f"Review commit: `{commit}`" in (target / "SUBMISSION.md").read_text()
    assert (project / "SUBMISSION.md").read_text() == "# Example capability\n"
    assert not (project / "submission.json").exists()
    assert "reviewCommit" not in json.loads((project / "submission-config.json").read_text())
    assert result["bytes"] == sum(path.stat().st_size for path in target.rglob("*") if path.is_file())


@pytest.mark.parametrize("change", ["tracked", "untracked"])
def test_release_manifest_rejects_uncommitted_source(project, tmp_path, change):
    committed_release(project)
    path = project / ("source/app/main.py" if change == "tracked" else "new-source.py")
    path.write_text("unreviewed source")
    target = tmp_path / "review"
    with pytest.raises(packaging.PackageError, match="clean source repository"):
        packaging.package_submission(target, project=project)
    assert not target.exists()
