@pytest.mark.parametrize("target_type", ["file", "directory", "broken"])
def test_included_symlink_rejected(project, tmp_path, target_type):
    external = tmp_path / "external"
    if target_type == "file":
        external.write_text("must not copy")
    elif target_type == "directory":
        external.mkdir()
        (external / "private.txt").write_text("must not copy")
    (project / "source/link").symlink_to(external)
    target = tmp_path / "review"
    with pytest.raises(packaging.PackageError, match="symlinks"):
        packaging.package_submission(target, project=project)
    assert not target.exists()


