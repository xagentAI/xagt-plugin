"""Packaging behavior: preserve review source and reject unsafe or partial artifacts."""

from pathlib import Path
import json
import subprocess

import pytest

from scripts import package_submission as packaging


@pytest.fixture
def project(tmp_path):
    root = tmp_path / "project"
    (root / "source" / "app").mkdir(parents=True)
    (root / "source" / "app" / "main.py").write_text("print('review source')\n")
    (root / "submission.json").write_text('{"draft": true}\n')
    return root


def test_copy_keeps_complete_source_and_drops_generated_trees(project, tmp_path):
    for directory in packaging.EXCLUDED_DIRS:
        generated = project / "source" / directory
        generated.mkdir()
        (generated / "local.key").write_text("local-only material")
        (generated / "python").symlink_to("missing-python")
    (project / "source" / ".env.example").write_text("COOKIE_SECURE=false\n")
    (project / "source" / "research.sqlite3").write_bytes(b"local data")
    (project / "source" / "run.log").write_text("local log")
    (project / "source" / "app" / "main.pyc").write_bytes(b"generated bytecode")
    (project / "source" / ".DS_Store").write_bytes(b"local metadata")
    target = tmp_path / "review"
    result = packaging.package_submission(target, project=project)
    names = {str(path.relative_to(target)) for path in target.rglob("*") if path.is_file()}
    assert names == {"source/app/main.py", "source/.env.example", "submission.json"}
    assert result["files"] == 3
    assert result["bytes"] == sum(path.stat().st_size for path in target.rglob("*") if path.is_file())
    assert (target / "source/app/main.py").read_bytes() == (project / "source/app/main.py").read_bytes()


@pytest.mark.parametrize("name", ["server.pem", "server.KEY", "client.p12", "client.pfx", ".env", ".env.local", ".dev.vars", ".dev.vars.production"])
def test_secret_file_types_rejected_before_copy(project, tmp_path, name):
    (project / name).write_text("inert test material")
    target = tmp_path / "review"
    with pytest.raises(packaging.PackageError, match="secret-bearing file type"):
        packaging.package_submission(target, project=project)
    assert not target.exists()


@pytest.mark.parametrize("secret", [
    "-----BEGIN " + "PRIVATE KEY-----",
    "AKIA" + "A" * 16,
    "ghp_" + "A" * 36,
    "sk-" + "a" * 20,
    "xoxb-" + "a" * 20,
])
def test_official_baseline_patterns_scan_all_files_without_echo(project, tmp_path, secret):
    (project / "verification").mkdir()
    (project / "verification" / "README.md").write_text("Test value: " + secret)
    target = tmp_path / "review"
    with pytest.raises(packaging.PackageError, match="possible secret") as exc:
        packaging.package_submission(target, project=project)
    assert secret not in str(exc.value)
    assert not target.exists()


